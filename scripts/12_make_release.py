"""Step 12 — build the public copy of the repository from this working folder.

    python scripts/12_make_release.py                    # -> ../library_rag_release (full record set)
    python scripts/12_make_release.py --records ids      # record identifiers only, no titles or abstracts
    python scripts/12_make_release.py --out D:/somewhere --clean

Only the files on the allow-list below are copied. Everything else in the working folder (old prototype,
drafts, local environments, indexes, logs with local paths) stays private. The copy is then scanned for
local paths, personal names and drafting notes, and a MANIFEST.csv with SHA-256 checksums is written.
Run it on the computer that holds the project, then publish the output folder.
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# what is published ---------------------------------------------------------------------------------------
ALLOW = [
    "requirements.txt", "config.yaml",
    "librag/**/*.py", "scripts/*.py", "tests/**/*.py", "tests/fixtures/**/*",
    "docs/annotation_guidelines.md", "docs/DETAILS.md",
    "data/queries/queries.xlsx", "data/qrels/**/*.txt",
    "data/annotation/judgements_A1.xlsx", "data/annotation/judgements_A2.xlsx",
    "data/annotation/pool_manifest.csv", "data/annotation/known_item_qrels.csv",
    "data/annotation/adjudication_needed.xlsx", "data/annotation/pilot1/*", "data/annotation/pilot2/*",
    "data/raw/oai/*/*/HARVEST_INFO.txt",
    "results/environment.json", "results/tables/*", "results/runs/*", "results/per_query/*",
    "results/figures/*",
    "results/generation/responses.jsonl", "results/generation/responses_verified.jsonl",
    "results/generation/human_eval_A1.xlsx", "results/generation/human_eval_A2.xlsx",
    "results/generation/human_eval_key.csv", "results/generation/human_eval_design.csv",
    "results/generation/models.json",
]
RECORDS = "data/processed/records.jsonl"

# never published, even if a pattern above would match -----------------------------------------------------
DENY = re.compile(r"(^|/)(\.venv|\.idea|__pycache__|chroma_db[^/]*|indexes|logs)(/|$)|\.pyc$|\.docx$|"
                  r"(^|/)(README_AR\.md|METHODOLOGY\.md|app\.py|main\.py|rag_core\.py|library_catalog\.csv)$|"
                  r"(^|/)Figure[^/]*$")

# text that must not appear in published code, configuration or documentation -----------------------------
SCAN_SUFFIXES = {".py", ".md", ".yaml", ".yml", ".json", ".txt", ".cfg", ".toml"}
SCAN_SKIP = re.compile(r"^(data/qrels/|results/runs/|data/annotation/|scripts/12_make_release\.py$)")
FORBIDDEN = [r"[A-Za-z]:\\Users\\", r"/Users/[A-Za-z]", r"\bSaif\b", r"\bArwa\b", r"\bClaude\b", r"\bAnthropic\b",
             r"prose in your own words", r"AI-usage rule", r"How to use this draft", r"METHODOLOGY\.md", r"Methodology_v2", r"README_AR", r"\u0628\u0623\u0633\u0644\u0648\u0628\u0643"]

README = """# {title}

Code, configuration, test collection and results of the study above.

| Folder | Content |
|---|---|
| `config.yaml` | every experimental setting (single source of truth) |
| `librag/` | harvesting (OAI-PMH Dublin Core; MARC21 and CSV readers), Arabic/English text processing, BM25, dense and hybrid retrieval, prompts, Ollama client, citation verification, metrics and statistics |
| `scripts/00`–`12` | the experiment step by step |
| `docs/annotation_guidelines.md` | query-writing, relevance-judgement and human-evaluation protocol given to the librarians |
| `docs/DETAILS.md` | implementation details summarised in the article (generated by `scripts/11_make_details.py`) |
| `data/queries/`, `data/qrels/`, `data/annotation/` | the 80 test queries, relevance judgements of both librarians, pooled pairs, pilot rounds |
| `data/processed/` | {records_line} |
| `results/` | tables, run files, per-query scores, figures, model responses and the human validation of the citation detector |
| `tests/` | unit tests and an end-to-end test on a synthetic fixture (not research data) |

## Reproduce

```bash
pip install -r requirements.txt          # install PyTorch with CUDA first
python -m unittest discover -s tests -v
python scripts/00_check_environment.py
python scripts/01_collect_records.py     # optional: re-harvest (the collection changes over time)
python scripts/02_prepare_dataset.py
python scripts/03_build_indexes.py
python scripts/06_eval_retrieval.py
python scripts/07_run_generation.py      # needs Ollama with the four models in config.yaml
python scripts/08_eval_generation.py
python scripts/09_import_human_eval.py
python scripts/10_make_figures.py
```

Steps 04 and 05 created and imported the relevance-judgement workbooks; their outputs are included, so they need
not be run again. Search indexes (`data/indexes/`) are not included because step 03 rebuilds them, and the raw
OAI-PMH responses are not included because of their size (harvest provenance is in `data/raw/oai/*/HARVEST_INFO.txt`).
`MANIFEST.csv` lists every file with its SHA-256 checksum.
"""


def sha256(p: Path) -> str:
    h = hashlib.sha256()
    with open(p, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default=str(ROOT.parent / f"{ROOT.name}_release"))
    ap.add_argument("--records", choices=["full", "ids"], default="full",
                    help="full = records.jsonl as used in the experiment; ids = record identifiers only")
    ap.add_argument("--title", default="Can Small Local Language Models Recommend Library Resources Without "
                                       "Inventing Them? Evidence from Arabic\u2013English Academic Journal Metadata")
    ap.add_argument("--clean", action="store_true", help="delete the output folder first")
    args = ap.parse_args()
    out = Path(args.out).resolve()
    if ROOT == out or ROOT in out.parents:
        sys.exit("the output folder must be outside the project folder")
    if out.exists() and any(out.iterdir()):
        # a folder made earlier by this script (it has MANIFEST.csv) is rebuilt; any other folder needs --clean
        if not (args.clean or (out / "MANIFEST.csv").exists()):
            sys.exit(f"{out} is not empty and was not made by this script; add --clean to replace it")
        shutil.rmtree(out)
    out.mkdir(parents=True, exist_ok=True)

    files = set()
    for pattern in ALLOW:
        files.update(p for p in ROOT.glob(pattern) if p.is_file())
    files = sorted(p for p in files if not DENY.search(p.relative_to(ROOT).as_posix()))
    try:                                   # harvest provenance only for the journals of the study
        import yaml
        cfg = yaml.safe_load((ROOT / "config.yaml").read_text(encoding="utf-8"))
        studied = {j for src in cfg["dataset"]["sources"] for j in src.get("journals", [])}
        files = [p for p in files if not (p.name == "HARVEST_INFO.txt" and p.parent.name not in studied)]
    except Exception as exc:               # noqa: BLE001
        print("note: could not read config.yaml to filter harvest folders:", exc)
    missing = [pat for pat in ALLOW if not any(ROOT.glob(pat))]

    copied = []
    for p in files:
        rel = p.relative_to(ROOT).as_posix()
        dst = out / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(p, dst)
        copied.append(rel)

    rec = ROOT / RECORDS
    if rec.exists():
        dst = out / RECORDS
        dst.parent.mkdir(parents=True, exist_ok=True)
        if args.records == "full":
            shutil.copy2(rec, dst)
            copied.append(RECORDS)
            records_line = "`records.jsonl`: the 17,128 cleaned records used in the experiment"
        else:
            ids = out / "data/processed/record_ids.txt"
            with open(rec, encoding="utf-8") as fh, open(ids, "w", encoding="utf-8") as fo:
                for line in fh:
                    fo.write(json.loads(line)["id"] + "\n")
            copied.append("data/processed/record_ids.txt")
            records_line = ("`record_ids.txt`: identifiers of the records used (re-harvest with step 01 and keep "
                            "these identifiers)")
    else:
        records_line = "not included"
    (out / "README.md").write_text(README.format(title=args.title, records_line=records_line), encoding="utf-8")
    copied.append("README.md")
    (out / ".gitignore").write_text("__pycache__/\n*.pyc\ndata/indexes/\nresults/logs/\n", encoding="utf-8")
    copied.append(".gitignore")

    problems = []
    for rel in copied:
        p = out / rel
        if p.suffix.lower() not in SCAN_SUFFIXES or SCAN_SKIP.search(rel):
            continue
        text = p.read_text(encoding="utf-8", errors="replace")
        for pat in FORBIDDEN:
            for m in re.finditer(pat, text):
                line = text.count("\n", 0, m.start()) + 1
                problems.append(f"{rel}:{line}: '{m.group(0)}'")

    with open(out / "MANIFEST.csv", "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(["path", "bytes", "sha256"])
        for rel in sorted(copied):
            p = out / rel
            w.writerow([rel, p.stat().st_size, sha256(p)])

    size = sum((out / r).stat().st_size for r in copied) / 1e6
    print(f"release folder: {out}\nfiles: {len(copied)} ({size:.1f} MB)")
    if missing:
        print("allow-list entries with no file (check):", *missing, sep="\n  ")
    big = [r for r in copied if (out / r).stat().st_size > 50e6]
    if big:
        print("files over 50 MB (GitHub warns; over 100 MB is refused):", *big, sep="\n  ")
    if problems:
        print("\nSTOP — remove or edit these before publishing:", *problems, sep="\n  ")
        sys.exit(1)
    print("scan: no local paths, personal names or drafting notes found")


if __name__ == "__main__":
    main()
